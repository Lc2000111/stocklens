// POST to an agent endpoint and render the answer into `out`
async function runAgent(url, body, out, btn, thinkingText) {
  btn.disabled = true;
  out.innerHTML = `<div class="ai-thinking"><span class="dot"></span>${thinkingText}</div>`;
  try {
    const res = await fetch(url, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body || {}) });
    const d = await res.json();
    if (!res.ok || d.error) throw new Error(d.error || "Request failed");
    out.innerHTML = `<div class="ai-out">${renderMarkdown(d.markdown)}</div>
      <div class="ai-meta">Generated by ${d.model || "gpt-6-luna"} via Portkey from StockLens data · AI can make mistakes; check key numbers · not investment advice</div>`;
    return d;
  } catch (e) {
    out.innerHTML = `<div class="ai-err">AI request failed: ${e.message.replace(/</g, "&lt;")}</div>`;
  } finally {
    btn.disabled = false;
  }
}
